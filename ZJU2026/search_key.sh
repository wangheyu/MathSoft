#!/bin/bash

# ------------------------------------------------------------
# 脚本功能：
#   在指定目录中递归查找所有文本文件，
#   找出其中包含指定关键字的文件，
#   并输出这些文件的路径。
#
# 用法：
#   bash find_keyword.sh DIRECTORY KEYWORD
#
# 例如：
#   bash find_keyword.sh . bash
# ------------------------------------------------------------

# ------------------------------------------------------------
# 第一步：检查命令行参数个数
# $# 表示传给脚本的参数个数
# 这里要求至少有两个参数：
#   $1 = 要搜索的目录
#   $2 = 要查找的关键字
# 如果参数不足，就输出用法说明并退出
# ------------------------------------------------------------
if [ $# -lt 2 ]
then
  echo "Usage: bash find_keyword.sh DIRECTORY KEYWORD"
  exit 1
fi

# ------------------------------------------------------------
# 第二步：把命令行参数保存到变量中
# 这样写更清晰，也便于后面重复使用
# search_dir 表示要搜索的目录
# keyword 表示要查找的关键字
# ------------------------------------------------------------
search_dir="$1"
keyword="$2"

# ------------------------------------------------------------
# 第三步：检查给出的目录是否真的存在，并且是目录
# -d 用来判断一个路径是否是目录
# 如果不是目录，就报错并退出
# ------------------------------------------------------------
if [ ! -d "$search_dir" ]
then
  echo "Error: '$search_dir' is not a directory."
  exit 1
fi

# ------------------------------------------------------------
# 第四步：递归查找目录下的所有普通文件
#
# find "$search_dir" -type f
# 含义：
#   在 search_dir 中递归查找 (-type f 表示普通文件)
#
# 然后把 find 的输出一行一行读入变量 file
#
# while read -r file
# 含义：
#   每次读取一个文件路径，存入变量 file
#   -r 的作用是防止反斜杠被特殊解释
# ------------------------------------------------------------
# find "$search_dir" -type f | while read -r file
# 改成下面这句，则会忽略所有隐藏目录
find "$search_dir" -type d -path '*/.*' -prune -o -type f -print | while read -r file
do

  # ----------------------------------------------------------
  # 第五步：判断当前文件是否是文本文件
  #
  # file "$file"
  #   用 file 命令查看文件类型
  # 这里可能需要安装 file
  # sudo apt install file
  #
  # grep -q 'text'
  #   如果输出中包含 text，就认为它是文本文件
  #   -q 表示 quiet，不显示匹配内容，只关心是否匹配成功
  #
  # 注意：
  #   这里是“粗略判断”，适合教学用途；
  #   并不是所有现实中的文本文件判断都这么简单。
  # ----------------------------------------------------------
  if file "$file" | grep -q 'text'
  then

    # --------------------------------------------------------
    # 第六步：在文本文件中查找指定关键字
    #
    # grep -q -- "$keyword" "$file"
    #
    # 含义：
    #   在文件 "$file" 中搜索 "$keyword"
    #
    # 参数说明：
    #   -q   : 安静模式，不输出匹配内容，只判断是否找到
    #   --   : 表示后面不再是选项，而是普通参数
    #          这样即使关键字以 - 开头，也不会被误认为 grep 选项
    #
    # 如果找到了关键字，就输出这个文件的路径
    # --------------------------------------------------------
    if grep -q -- "$keyword" "$file"
    then
      echo "$file"
    fi

  fi

done