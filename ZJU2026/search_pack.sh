#!/bin/bash

# ============================================================
# 脚本功能：
#   1. 在指定目录中递归搜索所有“指定后缀”的普通文件
#   2. 忽略隐藏目录（例如 .git、.idea、.vscode 等）
#   3. 将找到的文件统一打包成一个 zip 文件
#   4. 把 zip 文件保存到当前工作目录
#
# 用法：
#   bash pack_suffix_files.sh DIRECTORY SUFFIX [ZIP_NAME]
#
# 参数说明：
#   DIRECTORY   要搜索的目录
#   SUFFIX      文件后缀，例如 txt / py / md
#               也可以写成 .txt / .py / .md
#   ZIP_NAME    可选，输出的 zip 文件名
#
# 例如：
#   bash pack_suffix_files.sh . txt
#   bash pack_suffix_files.sh /home/user/project py code_backup.zip
#   bash pack_suffix_files.sh /home/user/docs .md notes.zip
#
# 注意：
#   1. 需要系统中安装 zip 命令
#   2. 本脚本能处理文件名中包含空格的情况
# ============================================================


# ============================================================
# 第一步：检查参数个数
#
# $# 表示传给脚本的参数个数
# 这里要求至少有 2 个参数：
#   $1 = 搜索目录
#   $2 = 文件后缀
#
# 第 3 个参数是可选的：
#   $3 = zip 文件名
# ============================================================
if [ $# -lt 2 ]
then
  echo "Usage: bash pack_suffix_files.sh DIRECTORY SUFFIX [ZIP_NAME]"
  exit 1
fi


# ============================================================
# 第二步：读取命令行参数
#
# search_dir : 用户要搜索的目录
# suffix     : 用户输入的后缀
# zip_name   : 用户指定的 zip 文件名（可选）
# ============================================================
search_dir="$1"
suffix="$2"
zip_name="$3"


# ============================================================
# 第三步：检查目录是否存在，并且确实是目录
#
# -d 用来判断一个路径是否是目录
# 如果不是目录，就报错退出
# ============================================================
if [ ! -d "$search_dir" ]
then
  echo "Error: '$search_dir' is not a directory."
  exit 1
fi


# ============================================================
# 第四步：检查系统是否安装了 zip 命令
#
# command -v zip
#   用来检查 shell 是否能找到 zip 这个命令
#
# >/dev/null 2>&1
#   表示把标准输出和错误输出都丢弃
#
# 如果没有安装 zip，则提示用户先安装
# ============================================================
if ! command -v zip >/dev/null 2>&1
then
  echo "Error: 'zip' command not found."
  echo "Please install it first."
  echo "For Ubuntu/Debian: sudo apt install zip"
  exit 1
fi


# ============================================================
# 第五步：规范化后缀写法
#
# 用户可能输入：
#   txt
#   .txt
#
# 我们统一把前面的点去掉，变成 txt
#
# ${suffix#.}
#   表示：如果 suffix 以 . 开头，就去掉最前面的一个 .
# ============================================================
suffix="${suffix#.}"


# ============================================================
# 第六步：把搜索目录转换成绝对路径
#
# 这样做的好处：
#   后面切换目录和计算相对路径时更稳定
#
# cd "$search_dir" && pwd
#   先进入该目录，再输出它的绝对路径
# ============================================================
search_dir="$(cd "$search_dir" && pwd)"


# ============================================================
# 第七步：确定输出 zip 文件名
#
# 如果用户没有提供 ZIP_NAME，
# 就自动生成一个带时间戳的名字，便于区分。
#
# 例如：
#   txt_files_20260402_091530.zip
# ============================================================
if [ -z "$zip_name" ]
then
  zip_name="${suffix}_files_$(date +%Y%m%d_%H%M%S).zip"
fi


# ============================================================
# 第八步：确保 zip 文件名以 .zip 结尾
#
# case ... esac 是 shell 中常见的模式匹配写法
# 如果名字本来就以 .zip 结尾，就不变
# 否则自动补上 .zip
# ============================================================
case "$zip_name" in
  *.zip) ;;
  *) zip_name="${zip_name}.zip" ;;
esac


# ============================================================
# 第九步：定义一个数组，用来保存找到的文件
#
# 为什么用数组？
#   因为可能找到很多文件
#   而且文件名可能有空格，数组更安全
#
# 这里保存的是“相对于搜索目录”的相对路径，
# 这样压缩包里的目录结构更清晰
# ============================================================
matched_files=()


# ============================================================
# 第十步：递归查找指定后缀的普通文件
#
# find "$search_dir"
#   从指定目录开始递归搜索
#
# -type d -path '*/.*' -prune
#   含义：
#   如果遇到隐藏目录（路径中某一层以 . 开头），就跳过不进入
#
# -o
#   表示“或者”
#
# -type f
#   只匹配普通文件
#
# -name "*.${suffix}"
#   只匹配指定后缀的文件
#   例如 suffix=txt，则匹配 *.txt
#
# -print0
#   用 NUL 字符作为分隔符输出文件名
#   这是处理“文件名中有空格、引号、特殊字符”的稳妥写法
#
# while IFS= read -r -d '' file
#   一次读取一个文件路径，读到变量 file 中
#   -d '' 表示以 NUL 为结束符
# ============================================================
while IFS= read -r -d '' file
do
  # ----------------------------------------------------------
  # 这里把绝对路径 file 转成相对路径
  #
  # 例如：
  #   search_dir=/home/user/project
  #   file=/home/user/project/src/main.py
  #
  # 则 rel_path=src/main.py
  #
  # ${file#"$search_dir"/}
  #   表示从 file 的开头删去“$search_dir/”
  # ----------------------------------------------------------
  rel_path="${file#"$search_dir"/}"

  # 输出找到的文件，方便用户查看
  echo "$file"

  # 加入数组
  matched_files+=("$rel_path")

done < <(
  find "$search_dir" \
    -type d -path '*/.*' -prune -o \
    -type f -name "*.${suffix}" -print0
)


# ============================================================
# 第十一步：检查是否真的找到了文件
#
# ${#matched_files[@]}
#   表示数组元素个数
#
# 如果一个都没找到，就提示并退出
# ============================================================
if [ ${#matched_files[@]} -eq 0 ]
then
  echo "No files with suffix '.${suffix}' were found."
  exit 0
fi


# ============================================================
# 第十二步：获取“当前工作目录”
#
# pwd 表示当前目录
# 这里的“当前目录”是你运行脚本时所在的目录
#
# 我们会把 zip 文件生成到这里
# ============================================================
current_dir="$(pwd)"


# ============================================================
# 第十三步：开始打包
#
# 为什么要先 cd 到 search_dir 再 zip？
#
# 因为这样 zip 文件里保存的是相对路径：
#   src/main.py
#   docs/readme.md
#
# 而不是一长串绝对路径：
#   /home/user/project/src/main.py
#
# 这样压缩包结构更自然
#
# 小括号 ( ... ) 表示在子 shell 中执行：
#   里面 cd 到 search_dir
#   不会影响外面脚本本身的当前目录
# ============================================================
(
  cd "$search_dir" || exit 1
  zip -r "$current_dir/$zip_name" "${matched_files[@]}"
)


# ============================================================
# 第十四步：输出结果信息
# ============================================================
echo
echo "Done."
echo "Found files: ${#matched_files[@]}"
echo "Zip archive created at: $current_dir/$zip_name"